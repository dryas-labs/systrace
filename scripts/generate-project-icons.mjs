// Geometry and role colors have one source: config/project-icon-shapes.json.
import { mkdir, readFile, readdir, realpath, unlink, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

async function assertInsideRepository(directory) {
  const location = relative(await realpath(root), await realpath(directory));
  if (!location || location === ".." || location.startsWith(`..${sep}`) || isAbsolute(location)) {
    throw new Error(`Icon directory must stay within the repository: ${directory}`);
  }
}

function render(shape, color, role, config) {
  const paths = shape.paths.map((d) => `<path d="${d}" vector-effect="non-scaling-stroke"/>`);
  for (const d of shape.dashedPaths ?? []) {
    paths.push(`<path d="${d}" stroke-dasharray="2 2" vector-effect="non-scaling-stroke"/>`);
  }
  // Paired roles share the same body position and proportions, leaving a fixed
  // lane for the Definition marker. Neutral navigation icons retain their layout.
  const body =
    role !== "neutral"
      ? `<g transform="${shape.bodyTransform}">${paths.join("")}</g>`
      : paths.join("");
  const marker = role === "definition" ? `<path d="${config.definitionMarker}"/>` : "";
  return `<!-- SPDX-License-Identifier: Apache-2.0 -->\n<!-- Generated by scripts/generate-project-icons.mjs; edit config/project-icon-shapes.json. -->\n<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" fill="none" stroke="${color}" stroke-width="${config.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${body}${marker}</svg>\n`;
}

export async function generateProjectIcons() {
  const config = JSON.parse(await readFile(join(root, "config/project-icon-shapes.json"), "utf8"));
  const output = join(root, "packages/extension/media/tree-icons");
  let count = 0;
  for (const [theme, palette] of Object.entries(config.palettes)) {
    const directory = join(output, theme);
    await mkdir(directory, { recursive: true });
    await assertInsideRepository(directory);
    const icons = new Map();
    for (const [family, shape] of Object.entries(config.families)) {
      for (const role of ["neutral", "definition", "usage"]) {
        const name = role === "neutral" ? `${family}.svg` : `${family}-${role}.svg`;
        icons.set(name, render(shape, palette[role], role, config));
      }
    }
    for (const [family, shape] of Object.entries(config.neutral)) {
      icons.set(`${family}.svg`, render(shape, palette.neutral, "neutral", config));
    }
    // Prune obsolete generated SVGs only in the bounded theme directories.
    // Non-SVG files and nested directories are never removed.
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (entry.isFile() && entry.name.endsWith(".svg") && !icons.has(entry.name)) {
        await unlink(join(directory, entry.name));
      }
    }
    for (const [name, contents] of icons) {
      await writeFile(join(directory, name), contents, "utf8");
      count += 1;
    }
  }
  return count;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const count = await generateProjectIcons();
  console.log(`Generated ${count} project tree icons from config/project-icon-shapes.json.`);
}
